// Embeds server/migrations/*.sql into server/src/migrations.generated.ts so serverless
// bundles (Netlify Functions) can migrate without access to the repository folder.
// Runs automatically before builds and tests; `--check` fails if the file is out of date.
import fs from 'node:fs';
import path from 'node:path';
const dir = path.resolve('server/migrations');
const out = path.resolve('server/src/migrations.generated.ts');
const files = fs.readdirSync(dir).filter((f) => /^\d+_.+\.sql$/.test(f)).sort();
const body = `// GENERATED by scripts/gen-migrations.mjs from server/migrations/*.sql. Do not edit.\nexport const EMBEDDED_MIGRATIONS: { name: string; sql: string }[] = [\n${files.map((f) => `  { name: ${JSON.stringify(f)}, sql: ${JSON.stringify(fs.readFileSync(path.join(dir, f), 'utf8'))} },`).join('\n')}\n];\n`;
if (process.argv.includes('--check')) {
  const cur = fs.existsSync(out) ? fs.readFileSync(out, 'utf8') : '';
  if (cur !== body) { console.error('server/src/migrations.generated.ts is out of date: run `npm run gen:migrations`'); process.exit(1); }
  console.log('embedded migrations up to date');
} else {
  fs.writeFileSync(out, body);
  console.log(`embedded ${files.length} migrations`);
}
